	// Сама ступенька: накопленная сумма импульса, приведённая к единице.
	// Считается один раз; в выходных отсчётах, поэтому от частот не зависит.
	inline const double *Step(double position)
	{
		static const std::array<double, Phases * Width> table = []()
		{
			std::array<double, Phases * Width> out{};
			for(uint32 phase = 0; phase < Phases; phase++)
			{
				int32 sum = 0;
				for(uint32 tap = 0; tap < Width; tap++)
				{
					sum += Impulse[phase][tap];
					out[phase * Width + tap] = static_cast<double>(sum) / Unit;
				}
			}
			return out;
		}();
		const uint32 phase = std::min<uint32>(Phases - 1,
			static_cast<uint32>(std::clamp(position, 0.0, 0.999999) * Phases));
		return table.data() + phase * Width;
	}

	// Одна дорожка звука: хранит ещё не выданный хвост ступенек.
	struct Lane
	{
		// queue — то, что ещё предстоит выдать, settle — то, что к концу хвоста
		// станет постоянным уровнем, base — уже ставший.
		std::array<double, Width + 1> queue{}, settle{};
		uint32 head = 0;
		double base = 0.0;

		void Reset()
		{
			queue.fill(0.0);
			settle.fill(0.0);
			head = 0;
			base = 0.0;
		}

		// Выход изменился на delta в точке position внутри текущего отсчёта.
		void Add(double delta, double position)
		{
			if(delta == 0.0)
				return;
			const double *shape = Step(position);
			for(uint32 tap = 0; tap < Width; tap++)
				queue[(head + tap) % (Width + 1)] += delta * shape[tap];
			settle[(head + Width) % (Width + 1)] += delta;
		}

		// Готовый отсчёт. Установившийся уровень прибавляется до выдачи, иначе
		// на последнем отсчёте ступеньки выход на один отсчёт провалился бы.
		double Pop()
		{
			const uint32 at = head;
			base += settle[at];
			settle[at] = 0.0;
			const double value = base + queue[at];
			queue[at] = 0.0;
			head = (at + 1) % (Width + 1);
			return value;
		}
	};
